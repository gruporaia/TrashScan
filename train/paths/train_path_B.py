def _predict_array_yolo(model, img_pil: Image.Image, device, imgsz: int,
                        conf: float = 0.001, iou: float = 0.6):
    """
    Runs YOLO on a PIL image.
    Returns normalized boxes [x1,y1,x2,y2] in [0,1], scores, classes.
    """
    result = model.predict(
        source=img_pil,
        conf=conf,
        iou=iou,
        imgsz=imgsz,
        device=device,
        verbose=False,
    )[0]

    if result.boxes is not None and len(result.boxes):
        boxes = result.boxes.xyxyn.cpu().numpy().astype(np.float32)
        scores = result.boxes.conf.cpu().numpy().astype(np.float32)
        classes = result.boxes.cls.cpu().numpy().astype(int)
    else:
        boxes = np.zeros((0, 4), dtype=np.float32)
        scores = np.zeros((0,), dtype=np.float32)
        classes = np.zeros((0,), dtype=int)

    return boxes, scores, classes


def _undo_hflip_boxes_norm(boxes_norm: np.ndarray) -> np.ndarray:
    """
    Undo horizontal flip for normalized xyxy boxes in [0,1].
    """
    if len(boxes_norm) == 0:
        return boxes_norm

    out = boxes_norm.copy()
    out[:, 0] = 1.0 - boxes_norm[:, 2]
    out[:, 2] = 1.0 - boxes_norm[:, 0]
    return out


def predict_tta_wbf_yolo(
    model,
    img_pil: Image.Image,
    device,
    scales=(512, 640, 768),
    use_hflip=True,
    wbf_iou=0.55,
    skip_box_thr=0.001,
    det_iou=0.6,
):
    """
    Multi-scale TTA + optional horizontal flip, fused with Weighted Boxes Fusion.
    This mirrors the Path A TTA/WBF evaluation protocol.
    Returns pixel-coordinate xyxy boxes, scores, classes.
    """
    if not ENSEMBLE_AVAILABLE:
        raise RuntimeError(
            "TTA+WBF requested but ensemble_boxes is not installed. "
            "Install with: pip install ensemble-boxes"
        )

    W, H = img_pil.size

    boxes_list = []
    scores_list = []
    labels_list = []

    for scale in scales:
        boxes, scores, classes = _predict_array_yolo(
            model=model,
            img_pil=img_pil,
            device=device,
            imgsz=scale,
            conf=skip_box_thr,
            iou=det_iou,
        )
        boxes_list.append(boxes.tolist())
        scores_list.append(scores.tolist())
        labels_list.append(classes.tolist())

        if use_hflip:
            img_flip = img_pil.transpose(Image.FLIP_LEFT_RIGHT)

            boxes_f, scores_f, classes_f = _predict_array_yolo(
                model=model,
                img_pil=img_flip,
                device=device,
                imgsz=scale,
                conf=skip_box_thr,
                iou=det_iou,
            )

            boxes_f = _undo_hflip_boxes_norm(boxes_f)

            boxes_list.append(boxes_f.tolist())
            scores_list.append(scores_f.tolist())
            labels_list.append(classes_f.tolist())

    fused_boxes, fused_scores, fused_labels = weighted_boxes_fusion(
        boxes_list,
        scores_list,
        labels_list,
        weights=[1.0] * len(boxes_list),
        iou_thr=wbf_iou,
        skip_box_thr=skip_box_thr,
    )

    if len(fused_boxes) == 0:
        return (
            np.zeros((0, 4), dtype=np.float32),
            np.zeros((0,), dtype=np.float32),
            np.zeros((0,), dtype=int),
        )

    fused_boxes = np.array(fused_boxes, dtype=np.float32)
    fused_scores = np.array(fused_scores, dtype=np.float32)
    fused_labels = np.array(fused_labels, dtype=int)

    # normalized xyxy -> pixel xyxy
    boxes_px = fused_boxes.copy()
    boxes_px[:, [0, 2]] *= W
    boxes_px[:, [1, 3]] *= H

    boxes_px[:, [0, 2]] = np.clip(boxes_px[:, [0, 2]], 0, W)
    boxes_px[:, [1, 3]] = np.clip(boxes_px[:, [1, 3]], 0, H)

    return boxes_px, fused_scores, fused_labels

# ─────────────────────────────────────────────────────────────────────────────
# YOLO-CROP DATASET
# Extracts 224×224 crops from detected YOLO boxes rather than GT boxes.
# Matches the evaluation protocol used in evaluate_path_B_combined.py.
# ─────────────────────────────────────────────────────────────────────────────

class YOLOCropDataset(Dataset):
    """
    Runs a frozen YOLO detector over every image in {split}/path_B/images,
    matches each detected box to the nearest GT box (IoU ≥ 0.5) to assign a
    label, crops and resizes to 224×224, then caches to disk.

    On subsequent epochs the cached crops are loaded directly (fast path).

    Args:
        data_root:  processed dataset root (contains train/val/test/path_B)
        split:      "train" | "val" | "test"
        detector:   Ultralytics YOLO model (frozen, for inference only)
        device:     inference device string, e.g. "0" or "cpu"
        conf:       YOLO detection confidence threshold (default 0.25)
        transform:  torchvision transform applied after crop
        cache_dir:  if provided, crops are saved here and reloaded on re-use
    """

    def __init__(
        self,
        data_root: Path,
        split:     str,
        detector,
        device:    str,
        conf:      float = 0.25,
        transform=None,
        cache_dir: Path = None,
        use_tta_wbf: bool = False,
        tta_scales=(512, 640, 768),
        tta_flip: bool = False,
        tta_wbf_iou: float = 0.55,
        tta_skip_box_thr: float = 0.001,
    ):
        self.transform = transform
        self.samples   = []          # [(crop_tensor_or_path, label)]
        self._use_cache = cache_dir is not None
        self.use_tta_wbf = use_tta_wbf
        self.tta_scales = tuple(tta_scales)
        self.tta_flip = tta_flip
        self.tta_wbf_iou = tta_wbf_iou
        self.tta_skip_box_thr = tta_skip_box_thr

        img_dir = Path(data_root) / split / "path_B" / "images"
        lbl_dir = Path(data_root) / split / "path_B" / "labels"
        assert img_dir.exists(), f"Image dir not found: {img_dir}"

        cache_root = Path(cache_dir) / split if cache_dir else None
        if cache_root and cache_root.exists():
            # ── fast path: load from cache ────────────────────────────────
            print(f"  [{split}] Loading YOLOCropDataset from cache: {cache_root}")
            for cls_dir in sorted(cache_root.iterdir()):
                if not cls_dir.is_dir():
                    continue
                try:
                    cls_idx = int(cls_dir.name)
                except ValueError:
                    continue
                for p in cls_dir.glob("*.jpg"):
                    self.samples.append((p, cls_idx))
            print(f"  [{split}] {len(self.samples)} cached crops loaded")
            return

        # ── slow path: detect + crop + (optionally cache) ─────────────────
        print(f"\n  [{split}] Building YOLOCropDataset via YOLO detection…")
        img_paths = sorted(img_dir.glob("*.jpg"))
        n_matched = 0
        n_skipped = 0

        if cache_root:
            cache_root.mkdir(parents=True, exist_ok=True)

        for img_path in tqdm(img_paths, desc=f"  [{split}] YOLO crops"):
            lbl_path = lbl_dir / img_path.with_suffix(".txt").name

            # load GT boxes + labels from YOLO txt
            gt_boxes, gt_classes = [], []
            if lbl_path.exists():
                img_pil = Image.open(img_path)
                W, H    = img_pil.size
                for line in lbl_path.read_text().strip().splitlines():
                    parts = line.split()
                    if len(parts) < 5:
                        continue
                    cls_id      = int(parts[0])
                    cx,cy,nw,nh = map(float, parts[1:5])
                    x1=(cx-nw/2)*W; y1=(cy-nh/2)*H
                    x2=(cx+nw/2)*W; y2=(cy+nh/2)*H
                    gt_boxes.append([x1,y1,x2,y2])
                    gt_classes.append(cls_id)
            else:
                img_pil = None

            if not gt_boxes:
                n_skipped += 1
                continue

            if self.use_tta_wbf:
                det_boxes, det_scores, det_classes = predict_tta_wbf_yolo(
                    model=detector,
                    img_pil=img_pil,
                    device=device,
                    scales=self.tta_scales,
                    use_hflip=self.tta_flip,
                    wbf_iou=self.tta_wbf_iou,
                    skip_box_thr=self.tta_skip_box_thr,
                    det_iou=0.6,
                )

                keep = det_scores >= conf
                det_boxes = det_boxes[keep]

            else:
                result = detector.predict(
                    str(img_path),
                    conf=conf,
                    iou=0.6,
                    device=device,
                    verbose=False,
                )[0]

                if result.boxes is None or len(result.boxes) == 0:
                    n_skipped += 1
                    continue

                det_boxes = result.boxes.xyxy.cpu().numpy()

            if len(det_boxes) == 0:
                n_skipped += 1
                continue

            gt_arr = np.array(gt_boxes, dtype=np.float32)
            gt_cls = np.array(gt_classes, dtype=int)

            # match each detected box → GT box via IoU
            iou_mat = _box_iou_np(det_boxes, gt_arr)   # (N_det, N_gt)
            matched_gt = set()

            order = np.argsort(-det_boxes[:, 2] * det_boxes[:, 3])  # large first
            for det_idx in order:
                best_gt    = int(np.argmax(iou_mat[det_idx]))
                best_iou   = float(iou_mat[det_idx, best_gt])
                if best_iou < 0.5 or best_gt in matched_gt:
                    continue
                matched_gt.add(best_gt)
                label = int(gt_cls[best_gt])

                # crop + resize
                x1,y1,x2,y2 = det_boxes[det_idx].astype(int)
                W2, H2 = img_pil.size
                x1=max(0,x1); y1=max(0,y1)
                x2=min(W2,x2); y2=min(H2,y2)
                if x2<=x1 or y2<=y1:
                    continue
                crop = img_pil.crop((x1,y1,x2,y2)).convert("RGB")
                crop = crop.resize((CROP_SIZE, CROP_SIZE), Image.BILINEAR)

                if cache_root:
                    cls_cache = cache_root / str(label)
                    cls_cache.mkdir(exist_ok=True)
                    crop_path = cls_cache / f"{img_path.stem}_{det_idx}.jpg"
                    crop.save(str(crop_path), quality=95)
                    self.samples.append((crop_path, label))
                else:
                    # keep in memory as tensor
                    t = transforms.ToTensor()(crop)
                    self.samples.append((t, label))
                n_matched += 1

        print(f"  [{split}] {n_matched} matched crops  "
              f"({n_skipped} images with no GT or no detections skipped)")

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        src, label = self.samples[idx]
        if isinstance(src, Path):
            img = read_image(str(src)).float() / 255.0
            if img.shape[0] == 1:
                img = img.repeat(3,1,1)
        else:
            img = src  # already a tensor
        if self.transform:
            img = self.transform(img)
        return img, label


def _box_iou_np(a: np.ndarray, b: np.ndarray) -> np.ndarray:
    """Compute IoU between two sets of xyxy boxes. Returns (N,M) matrix."""
    ax1,ay1,ax2,ay2 = a[:,0],a[:,1],a[:,2],a[:,3]
    bx1,by1,bx2,by2 = b[:,0],b[:,1],b[:,2],b[:,3]
    ix1 = np.maximum(ax1[:,None], bx1[None,:])
    iy1 = np.maximum(ay1[:,None], by1[None,:])
    ix2 = np.minimum(ax2[:,None], bx2[None,:])
    iy2 = np.minimum(ay2[:,None], by2[None,:])
    inter = np.maximum(0,ix2-ix1) * np.maximum(0,iy2-iy1)
    a_area = (ax2-ax1)*(ay2-ay1)
    b_area = (bx2-bx1)*(by2-by1)
    union  = a_area[:,None] + b_area[None,:] - inter
    return inter / (union + 1e-7)


