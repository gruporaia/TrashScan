def build_classifier(name: str) -> nn.Module:
    model_str, pretrained = CLASSIFIER_REGISTRY[name]
    model = timm.create_model(model_str, pretrained=pretrained,
                               num_classes=NUM_CLASSES)
    n = sum(p.numel() for p in model.parameters()) / 1e6
    print(f"  Built {name} ({model_str})  pretrained={pretrained}  {n:.1f}M params")
    return model


# ─────────────────────────────────────────────────────────────────────────────
# TRAINING LOOP
# ─────────────────────────────────────────────────────────────────────────────

def train_classifier(
    model, train_loader, val_loader,
    epochs, lr, device, class_weights, patience, output_dir,
) -> dict:
    model = model.to(device)
    class_weights = class_weights.to(device)

    criterion = nn.CrossEntropyLoss(weight=class_weights)
    optimizer = optim.AdamW(model.parameters(), lr=lr, weight_decay=5e-4)
    scheduler = optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=epochs)

    best_val_acc = 0.0
    best_epoch   = 0
    no_improve   = 0
    history      = []

    weights_dir = output_dir / "weights"
    weights_dir.mkdir(parents=True, exist_ok=True)

    for epoch in range(1, epochs + 1):
        # ── train ─────────────────────────────────────────────────────────
        model.train()
        tr_loss = tr_correct = tr_total = 0
        for imgs, labels in tqdm(train_loader,
                                  desc=f"  Ep {epoch}/{epochs} train",
                                  leave=False):
            imgs, labels = imgs.to(device), labels.to(device)
            optimizer.zero_grad()
            out  = model(imgs)
            loss = criterion(out, labels)
            loss.backward()
            optimizer.step()
            tr_loss    += loss.item() * imgs.size(0)
            tr_correct += (out.argmax(1) == labels).sum().item()
            tr_total   += imgs.size(0)

        scheduler.step()
        tr_acc  = tr_correct / tr_total
        tr_loss = tr_loss    / tr_total

        # ── val ───────────────────────────────────────────────────────────
        model.eval()
        v_loss = v_correct = v_total = 0
        all_preds, all_labels = [], []
        with torch.no_grad():
            for imgs, labels in tqdm(val_loader,
                                      desc=f"  Ep {epoch}/{epochs} val",
                                      leave=False):
                imgs, labels = imgs.to(device), labels.to(device)
                out    = model(imgs)
                v_loss += criterion(out, labels).item() * imgs.size(0)
                preds   = out.argmax(1)
                v_correct += (preds == labels).sum().item()
                v_total   += imgs.size(0)
                all_preds.extend(preds.cpu().numpy())
                all_labels.extend(labels.cpu().numpy())

        v_acc  = v_correct / v_total
        v_loss = v_loss    / v_total
        v_f1   = f1_score(all_labels, all_preds,
                          labels=list(range(NUM_CLASSES)),
                          average="macro", zero_division=0)

        print(f"  Ep {epoch:3d}/{epochs} | "
              f"train loss={tr_loss:.4f} acc={tr_acc:.4f} | "
              f"val loss={v_loss:.4f} acc={v_acc:.4f} f1={v_f1:.4f}")

        history.append({
            "epoch": epoch,
            "train_loss": round(tr_loss,5), "train_acc": round(tr_acc,5),
            "val_loss":   round(v_loss,5),  "val_acc":   round(v_acc,5),
            "val_f1":     round(v_f1,5),
            "lr": round(scheduler.get_last_lr()[0], 8),
        })

        if v_acc > best_val_acc:
            best_val_acc = v_acc
            best_epoch   = epoch
            no_improve   = 0
            torch.save(model.state_dict(), weights_dir / "best.pt")
        else:
            no_improve += 1
            if no_improve >= patience:
                print(f"  Early stopping at epoch {epoch} "
                      f"(best epoch {best_epoch}, val_acc={best_val_acc:.4f})")
                break

    pd.DataFrame(history).to_csv(output_dir / "history.csv", index=False)
    return {
        "best_epoch":     best_epoch,
        "best_val_acc":   round(best_val_acc, 5),
        "stopped_early":  no_improve >= patience,
        "epochs_trained": epoch,
    }


