def evaluate_on_test(model, test_loader, device, output_dir, clf_name) -> dict:
    model.eval()
    all_preds, all_labels, all_probs = [], [], []
    with torch.no_grad():
        for imgs, labels in tqdm(test_loader, desc="  Test"):
            out   = model(imgs.to(device))
            probs = torch.softmax(out, dim=1)
            all_preds.extend(out.argmax(1).cpu().numpy())
            all_labels.extend(labels.numpy())
            all_probs.extend(probs.cpu().numpy())

    all_preds  = np.array(all_preds)
    all_labels = np.array(all_labels)
    all_probs  = np.array(all_probs)
    labels_r   = list(range(NUM_CLASSES))

    per_class_ap = {}
    for c in range(NUM_CLASSES):
        gt_bin = (all_labels == c).astype(int)
        per_class_ap[COARSE_CLASSES[c]] = (
            round(float(average_precision_score(gt_bin, all_probs[:, c])), 5)
            if gt_bin.sum() > 0 else 0.0
        )

    # latency
    dummy = torch.zeros(1, 3, CROP_SIZE, CROP_SIZE).to(device)
    for _ in range(10):
        model(dummy)
    t0 = time.perf_counter()
    for _ in range(100):
        model(dummy)
    lat_ms = (time.perf_counter() - t0) / 100 * 1000

    metrics = {
        "classifier": clf_name,
        "accuracy":   round(float((all_preds == all_labels).mean()), 5),
        "precision":  round(float(precision_score(all_labels, all_preds,
                             labels=labels_r, average="macro",
                             zero_division=0)), 5),
        "recall":     round(float(recall_score(all_labels, all_preds,
                             labels=labels_r, average="macro",
                             zero_division=0)), 5),
        "f1":         round(float(f1_score(all_labels, all_preds,
                             labels=labels_r, average="macro",
                             zero_division=0)), 5),
        "latency_ms": round(lat_ms, 3),
    }
    metrics.update({f"AP_{cls}": v for cls, v in per_class_ap.items()})

    # confusion matrix
    cm = confusion_matrix(all_labels, all_preds, labels=labels_r)
    fig, ax = plt.subplots(figsize=(10, 8))
    ConfusionMatrixDisplay(cm, display_labels=COARSE_CLASSES).plot(
        ax=ax, colorbar=True, xticks_rotation=45)
    ax.set_title(f"Path B — {clf_name} — test confusion matrix")
    plt.tight_layout()
    plt.savefig(output_dir / f"confusion_matrix_{clf_name}.png", dpi=150)
    plt.close()

    with open(output_dir / "metrics.json", "w") as f:
        json.dump(metrics, f, indent=2)

    print(f"\n  [{clf_name}]  accuracy={metrics['accuracy']:.4f}  "
          f"f1={metrics['f1']:.4f}  latency={lat_ms:.2f}ms")
    return metrics


